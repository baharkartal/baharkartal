// Bundles public/ into worker/assets.gen.js so the worker serves the app itself
// (no separate asset upload needed).
import fs from 'node:fs';
import path from 'node:path';
const root = 'public', out = {};
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.json': 'application/json' };
const walk = d => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else { const ext = path.extname(p); const bin = ext === '.png'; out['/' + path.relative(root, p).split(path.sep).join('/')] = { t: TYPES[ext] || 'application/octet-stream', b: bin, d: fs.readFileSync(p, bin ? 'base64' : 'utf8') }; } } };
walk(root);
fs.writeFileSync('worker/assets.gen.js', '// generated by scripts/build-assets.mjs — do not edit\nexport default ' + JSON.stringify(out) + ';\n');
console.log('assets:', Object.keys(out).length, 'files');
